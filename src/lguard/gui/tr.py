_TABLES = {"de": DE, "es": ES, "en": EN}


def set_language(lang: str | None):
    global _lang
    if not lang or lang == "system":
        lang = QLocale.system().name()[:2]
    _lang = lang if lang in _TABLES else "en"


def language() -> str:
    return _lang


def _(text: str, **kw) -> str:
    out = _TABLES.get(_lang, {}).get(text) or EN.get(text) or text
    return out.format(**kw) if kw else out


